robust_symmetric_limit() {
    gmt grdinfo "$@" -C -L2 | awk '
        {
            lo = $12 - 2 * $13
            hi = $12 + 2 * $13
            if (lo < 0) lo = -lo
            if (hi < 0) hi = -hi
            if (lo > lim) lim = lo
            if (hi > lim) lim = hi
        }
        END {
            if (!(lim > 0)) lim = 1
            printf "%.12g\n", lim
        }
    '
}

make_symmetric_cpt() {
    local limit="$1"
    local output_cpt="$2"
    local lower upper increment

    lower="$(awk -v x="$limit" 'BEGIN {printf "%.12g", -x}')"
    upper="$(awk -v x="$limit" 'BEGIN {printf "%.12g",  x}')"
    increment="$(awk -v x="$limit" 'BEGIN {printf "%.12g", 2*x/100}')"

    gmt makecpt -Cvik -T"${lower}/${upper}/${increment}" -Z \
        > "$output_cpt"
}

